package dev.sandoretti.ukun.api.orders.application;

import dev.sandoretti.ukun.api.shared.web.Money;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * The open checkout — the {@code CheckoutAttempt} schema of the contract, and the body of
 * {@code POST /api/checkout/attempts}.
 *
 * <p><strong>{@code attemptId} is issued by the server</strong>, which is the decision of ADR-0016 in
 * one field: the browser sends it back verbatim as the {@code Idempotency-Key} header of
 * {@code POST /api/orders} and never invents one of its own. That removes the class of bug where a
 * key is regenerated by a re-render — something React had to guarantee and the server could not check.
 *
 * <p>{@code expiresAt} is thirty minutes out ({@code CheckoutAttempt.LIFETIME}). Past it, confirming
 * is {@code 410 CHECKOUT_EXPIRED} and the frontend reopens the checkout rather than charging a price
 * that has since moved.
 *
 * <p>It is assembled by {@code CheckoutService} rather than by a MapStruct mapper, the same call
 * {@code CartLineResponse} documents: three modules meet in it — the lines are this module's, the
 * names and prices came from {@code catalog}, {@code available} from {@code inventory} — so it is a
 * composition, not the projection of an entity.
 */
public record CheckoutAttemptResponse(
        UUID attemptId, List<CheckoutAttemptLineResponse> lines, @Money BigDecimal total, Instant expiresAt) {}
