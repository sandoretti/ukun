package dev.sandoretti.ukun.api.catalog.application;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;

/**
 * A new product (RF-10). The catalogue is <strong>global</strong>, not per store — unlike stock — so
 * nothing here carries a store: an admin creating a product is not creating it for their own shop.
 *
 * <p><strong>No image and no {@code isActive}.</strong> A product is born active and without a photo,
 * and the photo is uploaded afterwards against its own sub-resource ({@code PUT
 * /api/admin/products/{id}/image}). That is what keeps this operation pure JSON and confines multipart
 * handling to a single endpoint of the whole service ({@code docs/08-identidad-y-seguridad.md} §9).
 *
 * <p>{@code sku} is supplied by whoever creates the product and never generated by the database
 * (ADR-0015), and it is the one field that cannot be changed afterwards — see
 * {@link UpdateProductRequest}. The pattern is the one the database enforces, repeated here so a
 * malformed code comes back naming the field instead of as a conflict later.
 *
 * <p>{@code price} is {@code BigDecimal} with the bounds of the {@code Money} schema. Never a
 * {@code Float}: that is defect #5, and the legacy genuinely loses cents to it.
 */
public record CreateProductRequest(
        @NotBlank @Pattern(regexp = "^[A-Z0-9-]{3,32}$") @Schema(pattern = "^[A-Z0-9-]{3,32}$") String sku,
        @NotBlank @Size(min = 1, max = 255) String name,
        @NotBlank @Size(min = 1) String description,
        @NotNull @DecimalMin("0.00") @Digits(integer = 8, fraction = 2) BigDecimal price,
        @NotNull Long typeId) {}
